        IEnumerator Reveal(AlchemyResult r)
        {
            bool skip = PlayerPrefs.GetInt("alchemy.revealSeen", 0) == 1 && Director.ReducedMotion;
            RevealPlaying = true; skipReveal = false; BuildPanel();
            var t = stations.First(s => s.Id == "B01").transform; float start = Time.unscaledTime, length = skip ? 0 : 3.2f;
            Director.Go(Shot.Reveal, () =>
            {
                float k = Mathf.Clamp01((Time.unscaledTime - start) / Mathf.Max(.01f, length));
                var dir = Quaternion.Euler(0, -35 + 70 * k, 0) * -t.forward;
                return (t.position + dir * (1.7f - .4f * k) + Vector3.up * (1.5f - .2f * k), t.position + Vector3.up * (.8f + .25f * k), 46);
            }, .7f);
            lidOpen = true; sfx.PlayOneShot(thud, .8f);
            while (!skipReveal && Time.unscaledTime - start < length)
            {
                float k = (Time.unscaledTime - start) / length;
                if (revealLight) revealLight.intensity = r.success ? Mathf.Sin(k * Mathf.PI) * 2.2f : Mathf.Sin(k * Mathf.PI) * .8f;
                if (r.success && k > .45f && k < .5f) sfx.PlayOneShot(chime, .7f);
                if (r.success) steam.Emit(1); else smoke.Emit(2);
                yield return null;
            }
            if (revealLight) revealLight.intensity = 0;
            PlayerPrefs.SetInt("alchemy.revealSeen", 1);
            RevealPlaying = false;
            Active = stations.First(s => s.Id == "B01");
            ShowResult(r, true);
        }
        bool skipReveal;
        public void SkipReveal() { skipReveal = true; }

        IEnumerator Bottle()
        {
            if (bottleEmpty == null || bottleFilled == null) yield break;
            bottleEmpty.SetActive(false); bottleFilled.SetActive(true);
            var tr = bottleFilled.transform; var baseScale = tr.localScale;
            for (float k = 0; k < 1; k += Time.unscaledDeltaTime * 2.5f) { tr.localScale = baseScale * (1 + .25f * Mathf.Sin(k * Mathf.PI)); yield return null; }
            tr.localScale = baseScale;
        }

        void Gesture() { StartCoroutine(GestureRoutine()); }
        IEnumerator GestureRoutine()
        {
            var body = Walker != null ? Walker.transform.Find("Body") : null; var seal = Walker != null ? Walker.transform.Find("Body/Seal") : null;
            if (body == null) yield break;
            if (seal) seal.gameObject.SetActive(true);
            for (float k = 0; k < 1; k += Time.unscaledDeltaTime * 2.6f) { body.localRotation = Quaternion.Euler(Mathf.Sin(k * Mathf.PI) * 14, 0, 0); yield return null; }
            body.localRotation = Quaternion.identity; if (seal) seal.gameObject.SetActive(false);
        }

        void AnimateProps()
        {
            float T = Furnace != null ? (float)Furnace.T : 15; int burning = Furnace != null ? Furnace.Burning : 0; float vent = Furnace != null ? (float)Furnace.Vent : .5f;
            bool hot = T > 34;
            if (furnaceCold && furnaceHot) { furnaceCold.SetActive(!hot); furnaceHot.SetActive(hot); }
            if (fireLight) { fireLight.intensity = Mathf.Lerp(fireLight.intensity, burning > 0 ? .35f + T / 90f + Mathf.PerlinNoise(Time.time * 6, 0) * .25f : 0, .2f); fireLight.color = Color.Lerp(new Color(1, .55f, .25f), new Color(1, .85f, .6f), Mathf.InverseLerp(30, 95, T)); }
            var em = smoke.emission; em.rateOverTime = burning * (1 + vent * 3) + (T > 95 ? 25 : 0);
            var main = smoke.main; main.startColor = T > 95 ? new Color(.2f, .18f, .16f, .6f) : new Color(.75f, .75f, .72f, .35f);
            var sem = steam.emission; sem.rateOverTime = Furnace != null && Furnace.AllCharged && T > 40 ? 2 + (T - 40) / 8 : 0;
            fireAudio.volume = Mathf.Lerp(fireAudio.volume, Mathf.Clamp01(burning * .18f), .1f);
            if (damper) damper.localRotation = Quaternion.Euler(0, 0, vent * 80);
            lidBlend = Mathf.MoveTowards(lidBlend, lidOpen ? 1 : 0, Time.unscaledDeltaTime * 2.2f);
            if (lid && lidSeat)
            {
                var open = lidSeat.position + lidSeat.right * .66f - lidSeat.forward * .1f + Vector3.down * .74f; // rests on the hearth tiles
                float s = lidBlend * lidBlend * (3 - 2 * lidBlend);
                lid.position = Vector3.Lerp(lidSeat.position, open, s) + Vector3.up * Mathf.Sin(s * Mathf.PI) * .3f;
                lid.rotation = lidSeat.rotation * Quaternion.Euler(0, s * 25, 0);
            }
            bool cabinetOpen = Active != null && Active.Id == "B05";
            for (int i = 0; i < drawers.Count; i++)
            {
                var front = cabinetFront; float slide = cabinetOpen && i == 1 ? .2f : cabinetOpen && i == 0 ? .1f : 0;
                drawers[i].position = Vector3.Lerp(drawers[i].position, drawerHome[i] + front * slide, 1 - Mathf.Exp(-8 * Time.unscaledDeltaTime));
            }
        }

