        public void Open(AlchemyStation station)
        {
            Active = station; Walker.InputLocked = true; Walker.Face(station.Point);
            var t = station.transform; var fwd = -t.forward; // props face -Z local; player stands on that side
            switch (station.Id)
            {
                case "B05": Framed(Shot.Cabinet, t.position + fwd * 1.45f + Vector3.up * 1.2f, t.position + Vector3.up * .5f, 48); break;
                case "B07": Framed(Shot.Fuel, t.position + fwd * .95f + Vector3.up * 1.25f, t.position + Vector3.up * .22f, 50); break;
                case "B06": Framed(Shot.Fuel, t.position + fwd * 1.05f + Vector3.up * 1.2f, t.position + Vector3.up * .35f, 50); break;
                case "B11": Framed(Shot.Scroll, t.position + fwd * .62f + Vector3.up * .5f, t.position + Vector3.up * .2f, 46); break;
                case "TABLE":
                    var top = t.position + Vector3.up * .8f;
                    Framed(Shot.Table, top + fwd * 1.2f + Vector3.up * 1.05f, top - fwd * .05f, 52); break; // ~41° oblique top-down
                case "B01":
                    Director.Go(Shot.Brew, () =>
                    {
                        // Player sits at the left edge; the furnace lands left of centre, clear of the station panel.
                        var w = Walker.transform; var shoulder = w.position + Vector3.up * 1.95f + w.right * 1.0f - w.forward * 1.55f;
                        return (shoulder, t.position + Vector3.up * .5f + w.right * .42f, 50);
                    }); break;
            }
            Gesture();
            BuildPanel();
        }

        /// Close-ups keep the prop in the left two thirds: the station panel occupies the right third.
        void Framed(Shot shot, Vector3 pos, Vector3 look, float fov)
        {
            var right = Vector3.Cross(Vector3.up, (look - pos).normalized).normalized * Vector3.Distance(pos, look) * (compact ? .34f : .26f); // phone panel is wider relative to the screen
            Director.Go(shot, pos + right, look + right, fov);
        }

