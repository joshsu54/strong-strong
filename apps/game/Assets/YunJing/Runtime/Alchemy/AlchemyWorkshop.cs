        public void Adjust(int index, int delta)
        {
            var v = View; int max = Mathf.Min(v != null ? v.maxHerbEach : 4, Owned(Herbs[index]));
            Pick[index] = Mathf.Clamp(Pick[index] + delta, 1, Mathf.Max(1, max)); HerbsChosen = false; BuildPanel();
        }

        public void ChooseHerbs()
        {
            if (Owned(Herbs[0]) < Pick[0] || Owned(Herbs[1]) < Pick[1]) { Say("藥材不足，請減少份量或補充。"); return; }
            HerbsChosen = true; Say($"已備青靈草 {Pick[0]}、淨水蓮 {Pick[1]}。到柴箱取柴即開始。"); Guide(); BuildPanel();
        }

        public void AdjustFuel(int delta) { FuelPick = Mathf.Clamp(FuelPick + delta, 1, Mathf.Max(1, Mathf.Min(View?.maxFuel ?? 12, View?.fuel ?? 0))); BuildPanel(); }

        public void Begin()
        {
            if (!HerbsChosen) { Say("請先到藥櫃取出藥材。"); return; }
            var action = new GameAction { kind = "alchemy-begin", fuel = FuelPick, herbs = new[] {
                new AlchemyHerbLock { item = Herbs[0], quantity = Pick[0] }, new AlchemyHerbLock { item = Herbs[1], quantity = Pick[1] } } };
            Send(action, ok => { if (!ok) return; HerbsChosen = false; StartLocal(Session); Say("藥材與柴薪已移至工作台與爐邊（已扣除）。"); Back(); });
        }

        int Stamp() => Math.Max(CurrentTick, Math.Max(Furnace != null ? Furnace.Tick + 1 : 0, Log.Count > 0 ? Log[Log.Count - 1].t : 0));
        void Record(string k, string item = null, float v = 0) => Log.Add(new AlchemyEvent { t = Stamp(), k = k, item = item, v = v });

        public void DropOnMortar(string herb)
        {
            if (Furnace.IsCharged(herb)) return;
            if (DryIn.ContainsKey(herb)) { Say("先把藥材從晾藥籃取出。"); return; }
            if (Ground.Contains(herb)) { Say(HerbLabel(herb) + "已研成細末。"); return; }
            InMortar = herb; Say("在石臼上畫圈或連點研磨：" + HerbLabel(herb)); BuildPanel();
        }

        public void GrindStroke(float amount)
        {
            if (InMortar == null) return;
            float need = View != null ? View.grindStrokes : 12;
            GrindProgress.TryGetValue(InMortar, out var p); p += amount; GrindProgress[InMortar] = p;
            dust.Emit(4); if (!sfx.isPlaying) sfx.PlayOneShot(grind, .5f);
            if (p >= need) { Ground.Add(InMortar); Record("grind", InMortar); Say(HerbLabel(InMortar) + "研磨完成。"); InMortar = null; Gesture(); BuildPanel(); }
        }

        public void DropOnBasket(string herb)
        {
            if (Furnace.IsCharged(herb)) return;
            if (DryIn.ContainsKey(herb)) { DryOut(herb); return; }
            DryIn[herb] = Stamp(); Log.Add(new AlchemyEvent { t = DryIn[herb], k = "dry-in", item = herb });
            Say(HerbLabel(herb) + "放入晾藥籃，計時中。再拖一次取出。"); BuildPanel();
        }

        public void DryOut(string herb)
        {
            if (!DryIn.TryGetValue(herb, out var since)) return;
            int now = Stamp(); Log.Add(new AlchemyEvent { t = now, k = "dry-out", item = herb });
            DrySeconds.TryGetValue(herb, out var acc); DrySeconds[herb] = acc + (now - since) / 10f; DryIn.Remove(herb);
            Say($"{HerbLabel(herb)}取出，共晾 {DrySeconds[herb]:0.0} 息。"); BuildPanel();
        }

        public float Drying(string herb)
        {
            DrySeconds.TryGetValue(herb, out var acc);
            return DryIn.TryGetValue(herb, out var since) ? acc + (CurrentTick - since) / 10f : acc;
        }

        public string PrepLabel(string herb)
        {
            float d = Drying(herb); var v = View; float min = v != null ? v.drying.minSeconds : 8, max = v != null ? v.drying.maxSeconds : 24;
            bool dried = d >= min, scorched = d > max, ground = Ground.Contains(herb);
            string s = scorched ? "焦乾" : ground && dried ? "研末＋陰乾" : ground ? "研末" : dried ? "陰乾" : "生";
            if (DryIn.ContainsKey(herb)) s += $"（晾 {d:0.0} 息）";
            else if (GrindProgress.TryGetValue(herb, out var g) && !ground) s += $"（研磨 {g / (v != null ? v.grindStrokes : 12):P0}）";
            return s;
        }

        public void DropOnTray(string herb, bool main)
        {
            if (DryIn.ContainsKey(herb)) { Say("藥材還在晾藥籃中。"); return; }
            if (main) { MainHerb = herb; if (AuxHerb == herb) AuxHerb = null; } else { AuxHerb = herb; if (MainHerb == herb) MainHerb = null; }
            Compounded = false; BuildPanel();
        }

        public void Compound()
        {
            if (MainHerb == null || AuxHerb == null) { Say("君、臣兩格都要放上藥材。"); return; }
            Compounded = true; Gesture();
            var s = Session; int main = s.herbs.First(h => h.item == MainHerb).quantity, aux = s.herbs.First(h => h.item == AuxHerb).quantity;
            Say(main >= aux ? "配伍完成，藥材已分盤備妥。" : "配伍完成。提醒：君藥通常是份量較多的一味。");
            Guide(); BuildPanel();
        }

        public void Ladle(int delta)
        {
            Ladles = Mathf.Clamp(Ladles + delta, 0, 3); Say(delta > 0 ? $"舀起一瓢清水（手上 {Ladles} 瓢）。" : $"倒回一瓢（手上 {Ladles} 瓢）。"); Guide(); BuildPanel();
        }

        public void Lid()
        {
            lidOpen = !lidOpen; Record("lid", null, lidOpen ? 0 : 1); sfx.PlayOneShot(thud, .7f); Gesture(); BuildPanel();
        }

        public void PourWater()
        {
            if (Ladles <= 0) { Say("手上沒有水，請到陶水缸舀水。"); return; }
            if (!lidOpen) { Say("先開爐蓋。"); return; }
            Ladles--; Record("water"); steam.Emit(12); Say("注入一瓢水。"); Guide(); BuildPanel();
        }

        public void Charge(string herb)
        {
            if (!Compounded) { Say("先在工作台完成配伍。"); return; }
            if (!lidOpen) { Say("爐蓋未開，無法投料。"); return; }
            if (DryIn.ContainsKey(herb) || Furnace.IsCharged(herb)) return;
            bool first = !Herbs.Any(h => Furnace.IsCharged(h) || Log.Any(x => x.k == "charge" && x.item == h));
            Record("charge", herb); Gesture();
            if (first && !Session.charged)
                Send(new GameAction { kind = "alchemy-charge" }, ok => { if (!ok) Say("投料檢查點未寫入，請重試。"); }, quiet: true);
            Say(HerbLabel(herb) + "投入爐中。"); Guide(); BuildPanel();
        }

        public void AddFuel()
        {
            if (FuelLeft <= 0) { Say("爐邊的柴已用完。"); return; }
            FuelLeft--; Record("fuel"); sparks.Emit(15); Gesture(); BuildPanel();
        }

        public void Ignite()
        {
            if (Furnace.Loaded == 0 && !Log.Any(x => x.k == "fuel")) { Say("爐膛裡沒有柴。"); return; }
            Record("ignite"); sparks.Emit(30); Say("點火。"); Gesture(); BuildPanel();
        }

        public void SetVent(float v) { Record("vent", null, v); Say(v == 0 ? "排煙檔關閉：火勢收斂、保溫。" : v < 1 ? "排煙檔半開。" : "排煙檔全開：火旺、柴耗快。"); BuildPanel(); }

        public void Condense()
        {
            if (Waiting) return;
            Record("condense"); Gesture();
            AdvanceFurnace();
            if (Session != null && !Session.charged) { Send(new GameAction { kind = "alchemy-charge" }, ok => { if (ok) Finish(); else Log.RemoveAt(Log.Count - 1); }); return; }
            Finish();
        }

        void Finish()
        {
            var action = new GameAction { kind = "alchemy-finish", log = Log.ToArray() };
            Send(action, ok =>
            {
                if (!ok) { Log.RemoveAt(Log.Count - 1); return; }
                Stage = Stage.Result; StartCoroutine(Reveal(Session.result));
            });
        }

        public void Claim()
        {
            var r = Session?.result; if (r == null) return;
            Send(new GameAction { kind = "alchemy-claim" }, ok =>
            {
                if (!ok) return;
                if (r.success) { StartCoroutine(Bottle()); Say($"{OutputLabel(r.output)}（{r.label}）×{r.quantity} 已裝瓶放入行囊。"); }
                else Say("丹渣已收進行囊，可再試一爐。");
                Stage = Stage.Idle; Furnace = null; Log.Clear(); lidOpen = true; Active = null; Walker.InputLocked = false; Director.Explore(); Guide(); BuildPanel();
            });
        }

        public void Abandon()
        {
            bool charged = Session != null && Session.charged;
            Send(new GameAction { kind = "alchemy-abandon" }, ok =>
            {
                if (!ok) return;
