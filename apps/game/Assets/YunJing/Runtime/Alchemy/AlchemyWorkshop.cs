        void Send(GameAction action, Action<bool> done, bool quiet = false)
        {
            if (Api == null) return;
            if (!quiet) Waiting = true;
            StartCoroutine(SendRoutine(action, done, quiet));
        }

        // The state poll briefly marks the API busy; queue behind it instead of dropping the player's action.
        IEnumerator SendRoutine(GameAction action, Action<bool> done, bool quiet)
        {
            while (Api.Busy || Api.HasPending) yield return null;
            Api.Act(action, (ok, error) => { if (!quiet) Waiting = false; if (!ok) Say("未完成：" + error); done(ok); RefreshUi(); });
        }

